/**
 * สูตรคิดเงินของบิล — ใช้ร่วมกันระหว่าง worker และหน้าเว็บ
 *
 * ทำไมต้องเป็นไฟล์กลาง: ยอดที่ผู้ใช้เห็นตอนกรอก (คำนวณในเบราว์เซอร์เพื่อแสดง
 * สด) กับยอดที่บันทึกลงฐานข้อมูล (คำนวณใน worker) ต้องมาจากสูตรเดียวกันเสมอ
 * ถ้าต่างกันแม้แต่กฎการปัดเศษ ผู้ใช้จะเห็นยอดหนึ่งแล้วถูกเก็บอีกยอด ซึ่งเป็น
 * ความผิดพลาดที่ตรวจย้อนยากที่สุดในระบบนี้ — ก่อนหน้านี้มี 6 จุดที่เขียนสูตร
 * ซ้ำกัน (worker 3, client preview 3) และทุกจุดปัดครึ่ง (Math.round)
 *
 * กฎการปัดเศษ: **ปัดขึ้นเสมอ** สำหรับค่าน้ำและค่าไฟ ไม่ว่าทศนิยมจะเท่าไร
 * (หอเก็บเงินเป็นบาทถ้วน และไม่รับภาระเศษสตางค์ที่เกิดจากอัตราที่มีทศนิยม)
 */

/**
 * คิดจำนวนเงินจากหน่วยที่ใช้ × อัตราต่อหน่วย แล้วปัดขึ้นเป็นบาทถ้วน
 * ปัดผลคูณที่ 6 ตำแหน่งก่อน เพราะ float ทำให้ผลที่ลงตัวเกินไปนิดเดียว
 * (100 × 1.09 = 109.00000000000001) แล้วถูกปัดขึ้นเป็น 110
 */
export function chargeFromUnits(units: number, rate: number): number {
  return Math.ceil(Math.round(units * rate * 1e6) / 1e6);
}

/** ยอดเหมาจ่ายที่ผู้ใช้กรอก — ปัดขึ้นเป็นบาทถ้วนเช่นกัน */
export function chargeFromFlatAmount(amount: number): number {
  return Math.ceil(amount);
}

/**
 * ค่าไฟต่อหน่วยจากบิลการไฟฟ้ารวม: ยอดเงินในบิล ÷ หน่วยในบิล ปัดขึ้นเป็นทศนิยม 2 ตำแหน่ง
 * หน่วยต้องเป็นจำนวนเต็ม (ตามที่พิมพ์ในบิล) — คิดเป็นสตางค์จำนวนเต็มก่อนหาร
 * กันเศษของ float ดันให้ปัดขึ้นเกินจริง เช่น 520.00 ÷ 100 ต้องได้ 5.20 ไม่ใช่ 5.21
 */
export function rateFromBill(amount: number, units: number): number {
  return Math.ceil(Math.round(amount * 100) / units) / 100;
}

/** เพดานกันค่าที่ไม่ใช่จำนวนจำกัดหลุดเข้าสูตร (NaN จะกลายเป็น 0 เงียบ ๆ) */
export function isFiniteAmount(value: number): boolean {
  return Number.isFinite(value) && value >= 0;
}

/**
 * บิลไฟเหมาไม่ได้เก็บจำนวนหน่วยไว้ คิดจากเลขมิเตอร์ที่บันทึกไว้ทั้งสองครั้ง
 *
 * ทำไมต้องอยู่ไฟล์กลาง: หน้ารายการบิลกับไฟล์ส่งออกต้องแสดงหน่วยไฟของบิลเหมา
 * จ่ายเป็นตัวเลขเดียวกัน ถ้าต่างฝ่ายคิดเอง ไฟล์ที่เจ้าของเอาไปทำบัญชีจะไม่ตรงกับ
 * ที่เห็นบนจอ ซึ่งเป็นความผิดพลาดที่ตรวจย้อนได้ยาก
 *
 * รับแบบ structural ไม่ผูกกับชนิด Bill เพราะโมดูลนี้ต้องไม่พึ่งชนิดฝั่ง client
 */
export function electricUnitsOf(bill: {
  electricUnits: number | null;
  electricCurrent: number;
  electricPrevious: number;
}): number {
  return bill.electricUnits ?? bill.electricCurrent - bill.electricPrevious;
}
